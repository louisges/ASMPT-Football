create or replace function public.admin_add_player(player_name text, player_is_guest boolean)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  if player_name is null or char_length(btrim(player_name)) not between 1 and 60 then
    raise exception 'Player name must be between 1 and 60 characters.';
  end if;

  if player_is_guest is null then
    raise exception 'Specify whether this player is a guest.';
  end if;

  insert into public.players (name, is_guest)
  values (btrim(player_name), player_is_guest);
end;
$$;

create or replace function public.admin_update_player(
  target_player_id bigint,
  player_name text,
  player_is_guest boolean
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  old_name text;
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  if player_name is null or char_length(btrim(player_name)) not between 1 and 60 then
    raise exception 'Player name must be between 1 and 60 characters.';
  end if;

  if player_is_guest is null then
    raise exception 'Specify whether this player is a guest.';
  end if;

  select p.name into old_name
  from public.players p
  where p.id = target_player_id
  for update;

  if old_name is null then
    raise exception 'Player not found.';
  end if;

  if exists (
    select 1 from public.rsvps r
    where lower(r.name) = lower(btrim(player_name))
      and lower(r.name) <> lower(old_name)
  ) then
    raise exception 'That name already has an RSVP. Choose a different name.';
  end if;

  update public.players
  set name = btrim(player_name),
      is_guest = player_is_guest
  where id = target_player_id;

  update public.rsvps
  set name = btrim(player_name),
      response_type = case when player_is_guest then 'guest' else 'player' end,
      updated_at = now()
  where rsvps.player_id = target_player_id
     or (
       rsvps.player_id is null
       and rsvps.response_type = 'player'
       and lower(rsvps.name) = lower(old_name)
     );
end;
$$;

create or replace function public.admin_remove_player(player_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  delete from public.players where id = player_id;
  if not found then
    raise exception 'Player not found.';
  end if;
end;
$$;

create or replace function public.admin_list_players()
returns table(id bigint, name text)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  return query select p.id, p.name from public.players p order by p.name;
end;
$$;

