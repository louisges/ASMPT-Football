create function public.admin_reset_rsvps()
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  deleted_count integer;
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  perform 1 from public.attendance_settings where id = true for update;
  if not found then
    raise exception 'Attendance settings are missing. Run schema.sql in Supabase.';
  end if;

  delete from public.rsvps
  where created_at is not null;
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

create or replace function public.admin_set_player_limit(player_limit integer)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  current_attendance_status text;
  current_attending_count integer;
begin
  if not exists (
    select 1 from public.admin_users
    where email = lower(btrim(coalesce(auth.jwt() ->> 'email', '')))
  ) then
    raise exception 'Admin access required.';
  end if;

  if player_limit is not null and player_limit < 1 then
    raise exception 'Player limit must be at least 1, or blank for no limit.';
  end if;

  select attendance_status into current_attendance_status
  from public.attendance_settings
  where id = true
  for update;
  if not found then
    raise exception 'Attendance settings are missing. Run schema.sql in Supabase.';
  end if;

  if current_attendance_status = 'locked' and player_limit is not null then
    select count(*) into current_attending_count
    from public.rsvps
    where status = 'yes';
    if player_limit < current_attending_count then
      raise exception 'Unlock the teams before setting a limit below the current attending count.';
    end if;
  end if;

  update public.attendance_settings
  set max_players = player_limit
  where id = true;

  perform public.recalculate_rsvp_statuses(player_limit);
end;
$$;

