create table if not exists public.rsvps (
  name text not null check (char_length(btrim(name)) between 1 and 60),
  status text not null check (status in ('yes', 'maybe', 'no')),
  response_type text not null default 'guest' check (response_type in ('player', 'guest')),
  updated_at timestamptz not null default now()
);

alter table public.rsvps
  add column if not exists response_type text not null default 'guest'
  check (response_type in ('player', 'guest'));

create unique index if not exists rsvps_name_case_insensitive
  on public.rsvps (lower(name));

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  is_guest boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.players
  add column if not exists is_guest boolean not null default false;

alter table public.rsvps
  add column if not exists player_id bigint references public.players(id) on delete set null;

create unique index if not exists players_name_case_insensitive
  on public.players (lower(name));

create unique index if not exists rsvps_player_id_unique
  on public.rsvps (player_id)
  where player_id is not null;

create table if not exists public.admin_users (
  email text primary key check (email = lower(btrim(email)))
);

alter table public.rsvps enable row level security;
alter table public.players enable row level security;
alter table public.admin_users enable row level security;

