create or replace function public.recalculate_rsvp_statuses(player_limit integer)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  current_attendance_status text;
begin
  select attendance_status into current_attendance_status
  from public.attendance_settings
  where id = true;

  if not found then
    raise exception 'Attendance settings are missing. Run schema.sql in Supabase.';
  end if;

  if current_attendance_status = 'locked' then
    with attending_count as (
      select count(*) as total from public.rsvps where status = 'yes'
    ),
    ranked_waitlist as (
      select
        r.id,
        row_number() over (order by r.created_at asc, r.id asc) as waitlist_position
      from public.rsvps r
      where r.status = 'unable'
    )
    update public.rsvps r
    set status = 'yes'
    from ranked_waitlist, attending_count
    where r.id = ranked_waitlist.id
      and (
        player_limit is null
        or attending_count.total + ranked_waitlist.waitlist_position <= player_limit
      );
    return;
  end if;

  with ranked_rsvps as (
    select
      r.id,
      row_number() over (
        order by (r.response_type = 'guest') asc, r.created_at asc, r.id asc
      ) as place_number
    from public.rsvps r
  )
  update public.rsvps r
  set status = case
    when player_limit is null or ranked_rsvps.place_number <= player_limit then 'yes'
    else 'unable'
  end
  from ranked_rsvps
  where r.id = ranked_rsvps.id
    and r.status is distinct from case
      when player_limit is null or ranked_rsvps.place_number <= player_limit then 'yes'
      else 'unable'
    end;
end;
$$;

revoke all on function public.recalculate_rsvp_statuses(integer) from public;

create or replace function public.submit_rsvp(rsvp_name text, rsvp_type text)
returns text
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  selected_player_id bigint;
  selected_player_is_guest boolean;
  current_limit integer;
  current_attendance_status text;
  existing_status text;
  initial_status text;
  current_attending_count integer;
  submitted_status text;
begin
  if rsvp_name is null or char_length(btrim(rsvp_name)) not between 1 and 60 then
    raise exception 'Name must be between 1 and 60 characters.';
  end if;

  if rsvp_type is null or rsvp_type not in ('player', 'guest') then
    raise exception 'Name type must be player or guest.';
  end if;

  select max_players, attendance_status into current_limit, current_attendance_status
  from public.attendance_settings
  where id = true
  for update;

  if not found then
    raise exception 'Attendance settings are missing. Run schema.sql in Supabase.';
  end if;

  if current_attendance_status = 'closed' then
    raise exception 'Attendance is closed. No new RSVPs can be added.';
  end if;

  selected_player_id := null;
  selected_player_is_guest := false;
  if rsvp_type = 'player' then
    select id, is_guest into selected_player_id, selected_player_is_guest
    from public.players
    where lower(name) = lower(btrim(rsvp_name));

    if selected_player_id is null then
      raise exception 'Select a player from the player list.';
    end if;
  end if;

  select status into existing_status
  from public.rsvps
  where lower(name) = lower(btrim(rsvp_name));

  if current_attendance_status = 'locked' then
    if existing_status is not null then
      initial_status := existing_status;
    else
      select count(*) into current_attending_count
      from public.rsvps
      where status = 'yes';

      initial_status := case
        when current_limit is null or current_attending_count < current_limit then 'yes'
        else 'unable'
      end;
    end if;
  else
    initial_status := 'unable';
  end if;

  insert into public.rsvps (name, status, response_type, player_id, created_at, updated_at)
  values (
    btrim(rsvp_name),
    initial_status,
    case when rsvp_type = 'guest' or selected_player_is_guest then 'guest' else 'player' end,
    selected_player_id,
    now(),
    now()
  )
  on conflict (lower(name)) do update
    set name = excluded.name,
        status = case
          when current_attendance_status = 'locked' and existing_status is not null then existing_status
          else excluded.status
        end,
        response_type = excluded.response_type,
        player_id = excluded.player_id,
        updated_at = excluded.updated_at;

  if current_attendance_status <> 'locked' then
    perform public.recalculate_rsvp_statuses(current_limit);
  end if;
  select status into submitted_status
  from public.rsvps
  where lower(name) = lower(btrim(rsvp_name));

  return submitted_status;
end;
$$;

