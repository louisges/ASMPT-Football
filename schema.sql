drop function if exists public.submit_rsvp(text, text);

create or replace function public.submit_rsvp(rsvp_name text, rsvp_status text, rsvp_type text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  selected_player_id bigint;
  selected_player_is_guest boolean;
begin
  if rsvp_name is null or char_length(btrim(rsvp_name)) not between 1 and 60 then
    raise exception 'Name must be between 1 and 60 characters.';
  end if;

  if rsvp_status not in ('yes', 'maybe', 'no') then
    raise exception 'Answer must be yes, maybe, or no.';
  end if;

  if rsvp_type not in ('player', 'guest') then
    raise exception 'Name type must be player or guest.';
  end if;

  selected_player_id := null;
  selected_player_is_guest := false;
  if rsvp_type = 'player' then
    select id, is_guest into selected_player_id, selected_player_is_guest
    from public.players
    where lower(name) = lower(btrim(rsvp_name));

    if selected_player_id is null then
      raise exception 'Select a player from the player list.';
    end if;
  end if;

  insert into public.rsvps (name, status, response_type, player_id, updated_at)
  values (
    btrim(rsvp_name),
    rsvp_status,
    case when rsvp_type = 'guest' or selected_player_is_guest then 'guest' else 'player' end,
    selected_player_id,
    now()
  )
  on conflict (lower(name)) do update
    set name = excluded.name,
        status = excluded.status,
        response_type = excluded.response_type,
        player_id = excluded.player_id,
        updated_at = excluded.updated_at;
end;
$$;

revoke all on function public.submit_rsvp(text, text, text) from public;
grant execute on function public.submit_rsvp(text, text, text) to anon, authenticated;

